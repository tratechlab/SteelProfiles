/**
 * Calculates thickness-adjusted yield strength and ultimate strength (EN 10025-2 Table 7 / ISO 630)
 */
export function getEffectiveMechanicalProperties(
  grade: SteelGrade,
  thicknessMm: number
): { fy: number; fu: number; E: number; G: number; isReduced: boolean } {
  let fy = grade.fy;
  let fu = grade.fu;
  let isReduced = false;

  if (grade.thicknessRanges && grade.thicknessRanges.length > 0) {
    for (const range of grade.thicknessRanges) {
      if (thicknessMm <= range.maxT) {
        if (range.fy < grade.fy) isReduced = true;
        fy = range.fy;
        fu = range.fu;
        break;
      }
    }
  }

  return {
    fy,
    fu,
    E: grade.E,
    G: grade.G,
    isReduced,
  };
}

